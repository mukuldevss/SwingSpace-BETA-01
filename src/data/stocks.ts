// Deduplicate by symbol+exchange
const seen = new Set<string>();
export const STOCKS: Stock[] = ALL_STOCKS.filter((s) => {
  const key = `${s.symbol}:${s.exchange}`;
  if (seen.has(key)) return false;
  seen.add(key);
  return true;
});

export function searchStocks(query: string): Stock[] {
  if (!query || query.length < 1) return [];
  const q = query.toUpperCase().trim();
  const exact = STOCKS.filter((s) => s.symbol === q || s.name.toUpperCase() === q);
  const starts = STOCKS.filter(
    (s) => !exact.includes(s) && (s.symbol.startsWith(q) || s.name.toUpperCase().startsWith(q))
  );
  const contains = STOCKS.filter(
    (s) =>
      !exact.includes(s) &&
      !starts.includes(s) &&
      (s.symbol.includes(q) || s.name.toUpperCase().includes(q))
  );
  return [...exact, ...starts, ...contains].slice(0, 12);
}
